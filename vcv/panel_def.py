#!/usr/bin/env python3
"""Sary-Shagan VCV panel: the one place where positions are defined.

Writes res/SaryShagan.svg (text as paths, Rack's SVG renderer has no fonts) and
src/panel_layout.hpp (the same positions for the module widget).
    python3 panel_def.py
Built with the 3F4 panel kit (style/panel_3f4.py, rules in style/3F4_PANEL_STYLE.md).
Jacks: IN L/R bottom left, OUT L/R bottom right (as on all 3F4 modules); the
CV inputs keep Mesa's (4ms + Valley Audio) columns, the Freeze/Clear gates top right.
Needs fontTools and the DejaVu / Liberation fonts (FONT_DIR, LOGO_FONT to override).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "style"))
import panel_3f4 as p  # noqa: E402

pn = p.Panel(hp=24, title="SARY-SHAGAN")
HP, W, H, CX = pn.hp, pn.W, pn.H, pn.CX

# --- positions (mm, centres) ---------------------------------------------------
DISPLAY = pn.display(y=13.0)  # 256 × 64 NT pixels, 1:1 at 100 % zoom
POT_Y, POT_X = 50.0, (20.0, CX, W - 20.0)
ENC_Y, ENC_X = 79.0, (22.0, W - 22.0)
ENC_STEP_DX = p.ENC_STEP_DX
ENC_PUSH_Y = ENC_Y + p.ENC_PUSH_DY
CENTER_BTN_Y = 79.0
CENTER_BTN_X = (CX - 13.0, CX, CX + 13.0)  # FREEZE (button 3), CLEAR (button 4), MENU
SCREWS = pn.screws
JACK_X = pn.jack_columns(8)
JACK_Y = (p.JACK_LAST_ROW_Y - p.JACK_ROW_PITCH, p.JACK_LAST_ROW_Y)
# Inputs in module order: In L, In R, the ten CVs in Mesa's order (top row In Filt …
# Rvb Filt, bottom row Pre-Dly … Decay), then the Freeze and Clear gates.
INPUTS = [("IN L", 0, 1), ("IN R", 1, 1),
          ("IN FILT", 1, 0), ("DIFFUSION", 2, 0), ("SIZE", 3, 0), ("DRY/WET", 4, 0), ("RVB FILT", 5, 0),
          ("PRE-DLY", 0, 0), ("DEPTH", 2, 1), ("RATE", 3, 1), ("SHAPE", 4, 1), ("DECAY", 5, 1),
          ("FREEZE", 6, 0), ("CLEAR", 7, 0)]
OUTPUTS = [("OUT L", 6, 1), ("OUT R", 7, 1)]

# Pots: page SPACE on the label, INPUT · TONE · MOD underneath.
for x, name, alt in zip(POT_X, ("DIFFUSION", "SIZE", "DECAY"),
                        ("LEVEL · IN FILT · DEPTH", "PRE-DLY · DRY/WET · RATE",
                         "– · RVB FILT · SHAPE")):
    pn.big_knob(x, POT_Y, name, sub=alt)
pn.encoder(ENC_X[0], ENC_Y, "PAGE", steps=True, push="DIFFUSE")
pn.encoder(ENC_X[1], ENC_Y, "FINE", steps=True, push="TUNED")
for x, name in zip(CENTER_BTN_X, ("FREEZE", "CLEAR", "MENU")):
    pn.button(x, CENTER_BTN_Y, name)
# Jacks
pn.rule(98.6)
# Like the other 3F4 modules: IN L/R bottom left, OUT L/R bottom right. The CVs keep
# Mesa's columns (Mod Depth under Diffusion … Decay under Rvb Filt), gates top right.
pn.separator((JACK_X[5] + JACK_X[6]) / 2, JACK_Y[0])
for a, b in ((1, 2), (5, 6)):
    pn.separator((JACK_X[a] + JACK_X[b]) / 2, JACK_Y[1])
rings = {"IN L": p.RING_IN_L, "IN R": p.RING_IN_R, "OUT L": p.RING_OUT_L, "OUT R": p.RING_OUT_R}
for label, col, row in INPUTS + OUTPUTS:
    pn.jack(JACK_X[col], JACK_Y[row], label, rings.get(label))

pn.save(os.path.join(HERE, "res", "SaryShagan.svg"), os.path.join(HERE, "test", "panel_parts.txt"))
p.save_logo(os.path.join(HERE, "res", "3F4-logo.svg"))


def arr(xs):
    return ", ".join("%.3ff" % x for x in xs)


N = len(INPUTS)
hpp = """// Generated by panel_def.py — do not edit by hand.
#pragma once
#include <rack.hpp>

namespace panel_layout
{
using namespace rack;
constexpr int kHp = %d;
inline Vec DisplayPos() { return mm2px(Vec(%.3ff, %.3ff)); }
inline Vec DisplaySize() { return mm2px(Vec(%.3ff, %.3ff)); }
inline Vec Pot(int k) { const float x[3] = {%s}; return mm2px(Vec(x[k], %.3ff)); }
inline Vec Enc(int k) { const float x[2] = {%s}; return mm2px(Vec(x[k], %.3ff)); }
inline Vec EncStep(int k, int dir) { const float x[2] = {%s}; return mm2px(Vec(x[k] + dir * %.3ff, %.3ff)); }
inline Vec EncPush(int k) { const float x[2] = {%s}; return mm2px(Vec(x[k], %.3ff)); }
// 0 = FREEZE (NT button 3), 1 = CLEAR (button 4), 2 = MENU
inline Vec CenterButton(int k) { const float x[3] = {%s}; return mm2px(Vec(x[k], %.3ff)); }
// Inputs: In L, In R, 10 CVs (Mesa order), Freeze gate, Clear gate.
constexpr int kNumInputs = %d;
inline Vec InputPos(int k)
{
    const float x[%d] = {%s};
    const float y[%d] = {%s};
    return mm2px(Vec(x[k], y[k]));
}
inline Vec Screw(int k) { const float x[2] = {%s}; const float y[2] = {%s}; return mm2px(Vec(x[k], y[k])); }
constexpr int kNumScrews = 2;
inline Vec OutputPos(int k) { const float x[2] = {%s}; const float y[2] = {%s}; return mm2px(Vec(x[k], y[k])); }
} // namespace panel_layout
""" % (HP, DISPLAY[0], DISPLAY[1], DISPLAY[2], DISPLAY[3], arr(POT_X), POT_Y, arr(ENC_X), ENC_Y, arr(ENC_X),
       ENC_STEP_DX, ENC_Y, arr(ENC_X), ENC_PUSH_Y, arr(CENTER_BTN_X), CENTER_BTN_Y, N, N,
       arr(JACK_X[c] for _, c, _ in INPUTS), N, arr(JACK_Y[r] for _, _, r in INPUTS),
       arr(x for x, _ in SCREWS), arr(y for _, y in SCREWS),
       arr(JACK_X[c] for _, c, _ in OUTPUTS), arr(JACK_Y[r] for _, _, r in OUTPUTS))
open(os.path.join(HERE, "src", "panel_layout.hpp"), "w").write(hpp)

print("panel: %d HP, %d inputs, %d outputs" % (HP, len(INPUTS), len(OUTPUTS)))
